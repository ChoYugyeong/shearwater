// supervise stays in the foreground so systemd observes the actual server PID.
// It uses the same managed receipt as `up`: status/down retain PID-reuse checks,
// and a server restart adopts existing shims instead of restarting the apps.
func runSupervise(args []string) error {
	fs := flag.NewFlagSet("supervise", flag.ContinueOnError)
	var o opsOptions
	o.flags(fs)
	if err := parseOps(fs, args, &o); err != nil {
		return err
	}
	if err := privateDir(o.RunDir, true); err != nil {
		return err
	}
	b := make([]byte, 16)
	if _, err := rand.Read(b); err != nil {
		return err
	}
	return runServer(append([]string{"--managed=" + hex.EncodeToString(b)}, serverOptions(o)...))
}
func serverOptions(o opsOptions) []string {
	return []string{"--listen=" + o.Listen, "--data-dir=" + o.DataDir, "--config-dir=" + o.ConfigDir, "--run-dir=" + o.RunDir, "--log-dir=" + o.LogDir, "--containerd-socket=" + o.Socket, "--node-name=" + o.NodeName, "--runtime=" + o.Runtime}
}
func unitQuote(s string) (string, error) {
	if strings.ContainsAny(s, "\x00\r\n") {
		return "", fmt.Errorf("unit argument contains a control character")
	}
	s = strings.ReplaceAll(s, "\\", "\\\\")
	s = strings.ReplaceAll(s, "\"", "\\\"")
	s = strings.ReplaceAll(s, "%", "%%")
	s = strings.ReplaceAll(s, "$", "$$")
	return "\"" + s + "\"", nil
}
func serviceUnit(binary string, o opsOptions) (string, error) {
	if !filepath.IsAbs(binary) {
		return "", fmt.Errorf("binary must have an absolute path")
	}
	var words []string
	for _, v := range append([]string{binary, "supervise"}, serverOptions(o)...) {
		q, err := unitQuote(v)
		if err != nil {
			return "", err
		}
		words = append(words, q)
	}
	dependency := ""
	if o.Runtime == "containerd" && o.Socket == defaultSocket {
		dependency = "Wants=containerd.service\nAfter=containerd.service\n"
	}
	// Credentials/state explicitly request 0600/0700. A restrictive inherited
	// umask must not make generated Pod files or a custom runtime's rootfs
	// unreadable to non-root application processes.
	return "# Generated by sw service render. No containerd/Docker configuration is changed.\n[Unit]\nDescription=Shearwater local orchestrator\nAfter=network-online.target\nWants=network-online.target\n" + dependency + "StartLimitIntervalSec=60\nStartLimitBurst=10\n\n[Service]\nType=exec\nExecStart=" + strings.Join(words, " ") + "\nRestart=on-failure\nRestartSec=3\nTimeoutStopSec=20\nKillMode=process\nUMask=0022\n\n[Install]\nWantedBy=multi-user.target\n", nil
}
func runService(args []string, out io.Writer) error {
	if len(args) == 0 {
		return fmt.Errorf("use sw service render|install|start|stop|status|disable")
	}
	action := args[0]
	fs := flag.NewFlagSet("service "+action, flag.ContinueOnError)
	var o opsOptions
	o.flags(fs)
	name := fs.String("name", "shearwater", "unit name, beginning with shearwater")
	binary := fs.String("binary", "", "absolute permanent sw executable (default: this binary)")
	if err := parseOps(fs, args[1:], &o); err != nil {
		return err
	}
	if !strings.HasPrefix(*name, "shearwater") || strings.IndexFunc(*name, func(r rune) bool { return !(r >= 'a' && r <= 'z' || r >= '0' && r <= '9' || r == '-') }) >= 0 || len(*name) > 64 {
		return fmt.Errorf("invalid Shearwater unit name")
	}
	if *binary == "" {
		var err error
		*binary, err = os.Executable()
		if err != nil {
			return err
		}
	}
	unit, err := serviceUnit(*binary, o)
	if err != nil {
		return err
	}
	if action == "render" {
		_, err = io.WriteString(out, unit)
		return err
	}
	if os.Geteuid() != 0 {
		return needRoot("manage the system service")
	}
	if _, err := os.Stat("/run/systemd/system"); err != nil {
		return fmt.Errorf("systemd is not running; enable it for this WSL distribution first (see docs/automatic-start.md)")
	}
	systemctl := func(verb string) error {
		cmd := exec.Command("systemctl", verb, *name+".service")
		cmd.Stdout = out
		cmd.Stderr = os.Stderr
		return cmd.Run()
	}
	switch action {
	case "install":
		info, err := os.Stat(*binary)
		if err != nil {
			return err
		}
		if !info.Mode().IsRegular() || info.Mode().Perm()&0111 == 0 {
			return fmt.Errorf("binary must be an executable regular file")
		}
		if err := checkPrivateDir(filepath.Dir(*binary), false); err != nil {
			return err
		}
		path := filepath.Join("/etc/systemd/system", *name+".service")
		if err := checkPrivateDir(filepath.Dir(path), false); err != nil {
			return err
		}
		// Never replace somebody's unit or silently change an existing installation.
		// render lets an operator review an update before installing it themselves.
		f, err := os.OpenFile(path, os.O_CREATE|os.O_EXCL|os.O_WRONLY, 0644)
		if err != nil {
			return err
		}
		_, err = f.WriteString(unit)
		if err == nil {
			err = f.Sync()
		}
		closeErr := f.Close()
		if err != nil {
			return err
		}
		if closeErr != nil {
			return closeErr
		}
		if b, err := exec.Command("systemctl", "daemon-reload").CombinedOutput(); err != nil {
			return fmt.Errorf("unit written; daemon-reload failed: %s: %w", b, err)
		}
		if err := systemctl("enable"); err != nil {
			return err
		}
		fmt.Fprintf(out, "Installed and enabled %s. Review flags, then sw service start --name=%s. Existing server was not stopped.\n", path, *name)
		return nil
	case "start", "stop", "status", "disable":
		return systemctl(action)
	default:
		return fmt.Errorf("unknown service action %q", action)
	}
}
